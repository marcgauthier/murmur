// Buildstamp makes Go's build cache account for the external static library.
package main

import (
	"crypto/sha256"
	"fmt"
	"io"
	"os"
)

func main() {
	if len(os.Args) != 3 {
		panic("usage: buildstamp library output.go")
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		panic(err)
	}
	defer f.Close()
	h := sha256.New()
	if _, err = io.Copy(h, f); err != nil {
		panic(err)
	}
	data := []byte(fmt.Sprintf("// Code generated by buildstamp; DO NOT EDIT.\npackage murmur\nconst nativeBuildStamp = %q\n", fmt.Sprintf("%x", h.Sum(nil))))
	if err = os.WriteFile(os.Args[2], data, 0644); err != nil {
		panic(err)
	}
}
